// Generates script wallets and writes them to .env.local (gitignored). Prints addresses only, never keys.
// Refuses to overwrite an existing .env.local entry set.
import { Ed25519Keypair } from "@mysten/sui/keypairs/ed25519";
import { MultiSigPublicKey } from "@mysten/sui/multisig";
import { existsSync, readFileSync, writeFileSync } from "node:fs";
import { randomBytes } from "node:crypto";

const ENV = ".env.local";
if (existsSync(ENV) && /STEWARD_1_KEY=suiprivkey/.test(readFileSync(ENV, "utf8"))) {
  console.error(".env.local already has wallets. Delete it deliberately if you want new ones (funds would be orphaned).");
  process.exit(1);
}
const kp = () => Ed25519Keypair.generate();
const stewards = [kp(), kp(), kp()];
const keeper = kp();
const members = [kp(), kp(), kp(), kp(), kp()];
const msk = MultiSigPublicKey.fromPublicKeys({
  threshold: 2,
  publicKeys: stewards.map((s) => ({ publicKey: s.getPublicKey(), weight: 1 })),
});
const keeperMemwal = randomBytes(32).toString("hex");

const lines: string[] = [
  "# Eranos .env.local. Generated by scripts/gen-wallets.ts. NEVER commit. Fill the blank values.",
  "",
  "# ---- you provide ----",
  "TATUM_API_KEY=",
  "TATUM_ACCOUNT_ID=",
  "KV_REST_API_URL=",
  "KV_REST_API_TOKEN=",
  "",
  "# ---- chain config ----",
  "TATUM_SUI_GRAPHQL=https://sui-mainnet.gateway.tatum.io/graphql",
  "SUI_NETWORK=mainnet",
  "ERANOS_PKG=",
  "MEMWAL_PKG=0xe7c16fbea0560e7057e2bf7422feaa4fb313749fc69c9e9092fac7a33b81d7f5",
  "MEMWAL_REGISTRY=0x8bf82c9e09e36b8d1c38298f68b7cb68e7b8762887e7592add9986d5e9cf199f",
  "MEMWAL_SERVER_URL=https://relayer.memory.walrus.xyz",
  "USDC_TYPE=0xdba34672e30cb065b1f93e3ab55318768fd6fef66c15942c9f7cb846e2f900e7::usdc::USDC",
  "SPONSOR_CAP_PER_MEMBER_PER_ROUND_MIST=20000000",
  "ERANOS_SABOTAGE=",
  "",
  "# ---- generated: keeper ----",
  `KEEPER_SUI_KEY=${keeper.getSecretKey()}`,
  `KEEPER_SUI_ADDRESS=${keeper.toSuiAddress()}`,
  `KEEPER_MEMWAL_KEY=${keeperMemwal}`,
  `CRON_SECRET=${randomBytes(24).toString("hex")}`,
  "",
  "# ---- generated: stewards (2 of 3). STEWARD_*_KEY stay local, never in Vercel ----",
  `STEWARD_PUBKEYS=${stewards.map((s) => s.getPublicKey().toBase64()).join(",")}`,
  `STEWARD_MULTISIG_ADDRESS=${msk.toSuiAddress()}`,
  ...stewards.flatMap((s, i) => [`STEWARD_${i + 1}_KEY=${s.getSecretKey()}`, `STEWARD_${i + 1}_ADDRESS=${s.toSuiAddress()}`]),
  "",
  "# ---- generated: demo members (script wallets, the builder's own) ----",
  ...members.flatMap((m, i) => [`MEMBER_${i + 1}_KEY=${m.getSecretKey()}`, `MEMBER_${i + 1}_ADDRESS=${m.toSuiAddress()}`]),
  "",
  "# ---- filled by scripts after mainnet steps ----",
  "DEMO_CIRCLE_ID=",
  "DEMO_MEMORY_ACCOUNT_ID=",
  "ERANOS_URL=",
  "",
];
writeFileSync(ENV, lines.join("\n"), { mode: 0o600 });
console.log("Wrote .env.local\n");
console.log("FUND THESE ADDRESSES (mainnet):");
console.log(`  Stewards multisig (gas for create/admit/start_cycle): ${msk.toSuiAddress()}   needs ~0.5 SUI`);
console.log(`  Keeper (sponsor gas + payout gas):                    ${keeper.toSuiAddress()}   needs ~1.5 SUI`);
members.forEach((m, i) => console.log(`  Member ${i + 1}:                                                ${m.toSuiAddress()}   needs ~3 USDC (gas is sponsored)`));
console.log(`  Steward 1/2/3 single addresses need nothing (they only sign).`);
